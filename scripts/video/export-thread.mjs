#!/usr/bin/env node
// Export the real iMessage thread for the video's generated phone screen.
//
//   node scripts/video/export-thread.mjs            # from data/state.json (the server snapshots it)
//   node scripts/video/export-thread.mjs --server   # from the running server (GET /api/thread)
//
// Writes design/video/thread.json and design/video/thread.js (window.THREAD, for file:// pages)
// and copies every image the thread shows into design/video/media/<id>.png.
// Run it right after the take we use, before any reset (reset clears the thread).

import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const outDir = join(root, 'design', 'video');
const mediaOut = join(outDir, 'media');
const dataDir = join(root, 'data');
const useServer = process.argv.includes('--server');
const server = process.env.SERVER_URL || 'http://127.0.0.1:8787';

async function loadThread() {
  if (useServer) {
    const res = await fetch(`${server}/api/thread`);
    if (!res.ok) throw new Error(`GET /api/thread: ${res.status}`);
    const body = await res.json();
    return Array.isArray(body) ? body : body.thread ?? body.messages ?? [];
  }
  const state = JSON.parse(readFileSync(join(dataDir, 'state.json'), 'utf8'));
  return state.thread ?? [];
}

async function copyMedia(id) {
  mkdirSync(mediaOut, { recursive: true });
  const dest = join(mediaOut, `${id}.png`);
  if (useServer) {
    const res = await fetch(`${server}/api/media/${id}`);
    if (!res.ok) throw new Error(`GET /api/media/${id}: ${res.status}`);
    writeFileSync(dest, Buffer.from(await res.arrayBuffer()));
  } else {
    const src = join(dataDir, 'media', id);
    if (!existsSync(src)) throw new Error(`missing media file ${src}`);
    copyFileSync(src, dest);
  }
  return `media/${id}.png`;
}

const thread = await loadThread();
const messages = [];
for (const m of thread) {
  if (m.channel && m.channel !== 'imessage') continue; // dashboard-only lines never reached the phone
  const from = m.direction === 'in' ? 'me' : 'pacepay';
  if (m.imageUrl) {
    const id = m.imageUrl.split('/').pop();
    messages.push({ from, kind: 'image', image: await copyMedia(id), at: m.at });
  }
  if (m.text && m.text.trim()) messages.push({ from, kind: 'text', text: m.text, at: m.at });
}

if (!messages.length) {
  console.error('No iMessage thread found (was the server reset?). Nothing written.');
  process.exit(1);
}

const out = {
  placeholder: false,
  source: useServer ? `${server}/api/thread` : 'data/state.json',
  exportedAt: new Date().toISOString(),
  messages,
};
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'thread.json'), JSON.stringify(out, null, 2) + '\n');
writeFileSync(join(outDir, 'thread.js'), `// Generated by scripts/video/export-thread.mjs. Do not edit by hand.\nwindow.THREAD = ${JSON.stringify(out, null, 2)};\n`);
console.log(`Wrote ${messages.length} messages to design/video/thread.json and thread.js`);
